import { describe, expect, it } from 'vitest';
import { mkdtempSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { writeFiles } from '../src/writer';
import type { GeneratedFile } from '../src/generate';

const MARKER = 'Code generated by nofaultctl';

function file(path: string, content: string): GeneratedFile {
  return { path, content, kind: 'dto' };
}

function tmp(): string {
  return mkdtempSync(join(tmpdir(), 'codegen-'));
}

describe('writeFiles', () => {
  it('creates missing files including nested directories', () => {
    const dir = tmp();
    const r = writeFiles([file('a/b/c.ts', 'x')], { outDir: dir });
    expect(r.written).toEqual(['a/b/c.ts']);
    expect(readFileSync(join(dir, 'a/b/c.ts'), 'utf8')).toBe('x');
  });

  it('skips identical files and does not report them as changed', () => {
    const dir = tmp();
    writeFiles([file('a.ts', 'same')], { outDir: dir });
    const r = writeFiles([file('a.ts', 'same')], { outDir: dir });
    expect(r.written).toHaveLength(0);
    expect(r.changed).toHaveLength(0);
    // 内容没变却出现在"变更列表"里，会让使用方以为要重新编译/重新提交
  });

  it('overwrites files it previously generated even without force', () => {
    const dir = tmp();
    writeFileSync(join(dir, 'a.ts'), `// ${MARKER}\nold\n`);
    const r = writeFiles([file('a.ts', `// ${MARKER}\nnew\n`)], { outDir: dir });
    expect(r.written).toEqual(['a.ts']);
    expect(readFileSync(join(dir, 'a.ts'), 'utf8')).toContain('new');
  });

  it('never clobbers hand-edited files under the default policy', () => {
    // 这是最该被守住的一条：静默覆盖用户代码是生成器最恶劣的行为
    const dir = tmp();
    writeFileSync(join(dir, 'a.ts'), 'const myOwnCode = 1;\n');
    const r = writeFiles([file('a.ts', `// ${MARKER}\ngenerated\n`)], { outDir: dir });
    expect(r.written).toHaveLength(0);
    expect(r.skipped).toEqual(['a.ts']);
    expect(readFileSync(join(dir, 'a.ts'), 'utf8')).toBe('const myOwnCode = 1;\n');
  });

  it('honours policy=overwrite', () => {
    const dir = tmp();
    writeFileSync(join(dir, 'a.ts'), 'hand written\n');
    const r = writeFiles([file('a.ts', 'generated\n')], { outDir: dir, policy: 'overwrite' });
    expect(r.written).toEqual(['a.ts']);
    expect(readFileSync(join(dir, 'a.ts'), 'utf8')).toBe('generated\n');
  });

  it('honours policy=skip for everything existing', () => {
    const dir = tmp();
    writeFileSync(join(dir, 'a.ts'), `// ${MARKER}\nold\n`);
    expect(writeFiles([file('a.ts', 'new\n')], { outDir: dir, policy: 'skip' }).written).toHaveLength(0);
  });

  it('dryRun reports intent without touching the disk', () => {
    const dir = tmp();
    const r = writeFiles([file('a.ts', 'x')], { outDir: dir, dryRun: true });
    expect(r.written).toEqual(['a.ts']);
    expect(existsSync(join(dir, 'a.ts'))).toBe(false);
  });

  it('supports a custom marker so the policy can be pointed at other tools', () => {
    const dir = tmp();
    writeFileSync(join(dir, 'a.ts'), '// by other-tool\nold\n');
    expect(writeFiles([file('a.ts', 'new\n')], { outDir: dir, marker: 'by other-tool' }).written).toEqual(['a.ts']);
  });
});
